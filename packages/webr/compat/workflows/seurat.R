suppressPackageStartupMessages(library(Seurat))
data_dir <- Sys.getenv("COMPAT_DATA", "/data")
result <- function(key, value) cat(sprintf("RESULT %s %s\n", key, format(value, digits = 6)))
set.seed(42)

extracted <- file.path(tempdir(), "pbmc3k")
untar(file.path(data_dir, "pbmc3k.tar.gz"), exdir = extracted, tar = "internal")
counts <- Read10X(file.path(extracted, "filtered_gene_bc_matrices/hg19"))
pbmc <- CreateSeuratObject(counts, project = "pbmc3k", min.cells = 3, min.features = 200)
pbmc[["percent.mt"]] <- PercentageFeatureSet(pbmc, pattern = "^MT-")
pbmc <- subset(pbmc, subset = nFeature_RNA > 200 & nFeature_RNA < 2500 & percent.mt < 5)
pbmc <- NormalizeData(pbmc, verbose = FALSE)
pbmc <- FindVariableFeatures(pbmc, selection.method = "vst", nfeatures = 2000, verbose = FALSE)
pbmc <- ScaleData(pbmc, features = rownames(pbmc), verbose = FALSE)
pbmc <- RunPCA(pbmc, features = VariableFeatures(pbmc), verbose = FALSE)
pbmc <- FindNeighbors(pbmc, dims = 1:10, verbose = FALSE)
pbmc <- FindClusters(pbmc, resolution = 0.5, random.seed = 0, verbose = FALSE)
pbmc <- RunUMAP(pbmc, dims = 1:10, seed.use = 42, verbose = FALSE)
markers <- FindMarkers(pbmc, ident.1 = 2, min.pct = 0.25, verbose = FALSE)

print(DimPlot(pbmc, reduction = "umap", label = TRUE))
print(VlnPlot(pbmc, features = c("nFeature_RNA", "percent.mt"), ncol = 2))

result("cells", ncol(pbmc))
result("features", nrow(pbmc))
result("top_variable", VariableFeatures(pbmc)[1])
result("pc1_sdev", Stdev(pbmc, reduction = "pca")[1])
result("clusters", length(levels(Idents(pbmc))))
result("largest_cluster", max(table(Idents(pbmc))))
result("cluster2_top_marker", rownames(markers)[1])
